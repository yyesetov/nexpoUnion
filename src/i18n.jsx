function useI18n() {
  const [lang, setLang] = React.useState(() => localStorage.getItem('mangal.lang') || 'kz');
  React.useEffect(() => {
    localStorage.setItem('mangal.lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const t = I18N[lang];
  return { lang, setLang, t };
}

Object.assign(window, { I18N, useI18n });
